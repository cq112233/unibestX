/**
 * ═══════════════════════════════════════════════════════════════════════════
 *  换图标 / 换图标库：只改这个文件。改完在项目根目录跑一次 `pnpm icons`。
 * ═══════════════════════════════════════════════════════════════════════════
 *
 * 流程（不用改任何代码）：
 *   1. 去 iconfont.cn 的项目里增删图标，保存；
 *   2. 复制它的「Font class」的 CSS 链接 —— 形如
 *      https://at.alicdn.com/t/c/font_<项目号>_<hash>.css
 *      （增删图标后这个链接会变，所以每次都要重新复制一次）；
 *   3. 粘贴到下面 css；阿里项目里不想要的图标写进 exclude；
 *   4. 项目根目录跑 `pnpm icons`。
 *
 * 一条命令同时更新四处：小程序用的字体地址、图标名→码点表、Web/H5 的 @font-face、
 * 以及 App 端网页里内联的字体文件（App 端是字体焊进网页的，不重跑就还是旧字形）。
 *
 * `pnpm icons:check` 只校验不写盘 —— 用来发现「改了配置但忘了跑命令」。
 *
 * ⚠️ 为什么必须跑那条命令、不能纯手工改产物：图标码点表是编译期就要定的，
 *    App 端网页里的字体是 base64 焊死的 —— 两者都不是运行期能读变量解决的。
 */
export default {
  /**
   * 阿里图标库「Font class」的 CSS 链接。
   *
   * 这一个链接里装着生成所需的一切：字体文件地址（woff2/woff/ttf）
   * 和每个图标的码点（`.icon-<名字>:before { content: "\e602" }`）。
   * 当前指向：阿里图标库项目 5229558。
   */
  css: 'https://at.alicdn.com/t/c/font_5229558_ba6vyj2r9g5.css',

  /**
   * 阿里项目里还留着、但本项目不要的图标名：生成时跳过。
   *
   * 为什么需要它：图标表是那份 CSS 的镜像，而 CSS 里没有「我不要这个」这条信息 ——
   * 那个链接只会说「wuguan 存在，码点 EC5F」。「不想要」只存在你脑子里，
   * 所以不写在这里的话，它每次重新生成都会复活。
   *
   * 名字写错、或该图标已从阿里项目删掉 —— 都会直接报错退出，不会静默地少排除一个。
   * 想彻底干净：去阿里项目里删掉它，再把这一行清空。
   */
  exclude: ['wuguan'],

  /**
   * App 端演示页的兜底图标名（万一码点没传进来时显示的那一个）。
   *
   * 只写图标名、不写码点 —— 码点由生成时从上面那份 CSS 查出来写进演示页，
   * 所以换库后不会出现「兜底指着一个新库里没有的码点、一渲染就是豆腐块」。
   */
  fallbackIcon: 'gear'
};
